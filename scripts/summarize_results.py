"""Assemble docs/results/results_summary.md and results/tables/*.csv from saved result files only.

    python scripts/summarize_results.py
Sections whose inputs do not exist yet are skipped.
"""
from __future__ import annotations

import glob
import json
import pathlib

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
TAB = ROOT / "results/tables"
TAB.mkdir(parents=True, exist_ok=True)


def latest(pattern):
    hits = sorted(glob.glob(str(ROOT / pattern)))
    return pathlib.Path(hits[-1]) if hits else None


def md(df: pd.DataFrame, floatfmt=3) -> str:
    """Minimal markdown table (avoids an extra dependency)."""
    if not len(df):
        return "(none)"
    df = df.round(floatfmt)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main():
    out = ["# Results summary (generated by scripts/summarize_results.py from saved result files)", ""]
    full = latest("results/matrix/*_full_matrix_*")
    if full is None or not (full / "analysis/stability_summary.csv").exists():
        print("no full run analysis yet")
        return
    man = json.loads((full / "manifest.json").read_text())
    out += [f"Discovery run `{full.name}`: {man['n_folds']} folds, code commit `{man['git']['commit'][:8]}` (dirty={man['git']['dirty']}), runtime {man['runtime_seconds']}, samples {man['sample_definition']}.", ""]

    pm = pd.read_csv(full / "pooled_metrics.csv")
    perf = pm.groupby("config_id", sort=False).agg(roc_auc=("roc_auc", "mean"), roc_auc_ci_lo=("roc_auc_ci_lo", "mean"), roc_auc_ci_hi=("roc_auc_ci_hi", "mean"),
                                                   ap_normal=("ap_normal", "mean"), balanced_accuracy=("balanced_accuracy", "mean"), sensitivity=("sensitivity", "mean"),
                                                   specificity=("specificity", "mean"), f1_normal=("f1_normal", "mean")).reset_index()
    perf.to_csv(TAB / "table3_performance.csv", index=False)
    out += ["## Predictive performance (out-of-fold, mean of repeats; CI = mean of per-repeat bootstrap CIs)", md(perf), ""]

    ss = pd.read_csv(full / "analysis/stability_summary.csv")
    res = ss[ss.dimension == "resampling"].pivot(index="group", columns="k", values="phi_mean")
    res.columns = [f"phi_k{c}" for c in res.columns]
    rng = ss[(ss.dimension == "resampling") & (ss.k == 25)].set_index("group")[["phi_median", "phi_min", "phi_max", "phi_sd", "mean_set_size"]]
    t4 = res.join(rng).reset_index(); t4.to_csv(TAB / "table4_resampling_stability.csv", index=False)
    out += ["## Resampling stability (Nogueira Phi per 5-fold repeat, mean over repeats; k=25 spread)", md(t4), ""]
    within = ss[ss.dimension != "resampling"].pivot_table(index=["dimension", "group"], columns="k", values="phi_mean").reset_index()
    within.columns = [str(c) if not isinstance(c, int) else f"phi_k{c}" for c in within.columns]
    within.to_csv(TAB / "table4b_within_fold_stability.csv", index=False)
    out += ["## Model / explainer / combined / baseline / sensitivity agreement within folds (Phi)", md(within), ""]
    pooled = pd.read_csv(full / "analysis/pooled_resampling.csv"); pooled.to_csv(TAB / "table4c_pooled_resampling.csv", index=False)

    ovn = full / "analysis/observed_vs_null.csv"
    if ovn.exists():
        c = pd.read_csv(ovn)
        c25 = c[c.k == 25][["dimension", "group", "n_null_replicates", "obs_median", "obs_min", "obs_max", "null_median", "null_p2.5", "null_p97.5", "null_max", "median_difference", "frac_obs_repeats_above_null_p97.5"]]
        c25.to_csv(TAB / "table4d_observed_vs_null_k25.csv", index=False)
        out += ["## Observed vs permutation-label null (k=25; unit = one 5-fold repeat; descriptive, no p-value)", md(c25), ""]

    g25 = pd.read_csv(full / "analysis/gene_table_k25.csv")
    top = g25.head(30)[["gene", "mean_selection_frequency", "n_pipelines_ge50", "n_models_ge50", "n_explainers_ge50", "median_rank", "best_rank", "ttest_frequency", "frac_signed_positive", "consensus"]]
    top.to_csv(TAB / "table5_top_stable_genes.csv", index=False)
    out += ["## Top 30 genes by mean selection frequency at k=25", md(top), f"Genes meeting the pre-specified consensus rule: {int(g25.consensus.sum())}.", ""]

    ext = latest("results/external/*_gse65194")
    if ext and (ext / "summary.json").exists():
        s = json.loads((ext / "summary.json").read_text())
        out += ["## External replication (GSE65194)", "```json", json.dumps(s["primary_gene_level"], indent=1, default=str), "```",
                md(pd.read_csv(ext / "list_level_replication.csv")), "Sample-level (frozen LR on S_top25):", "```json", json.dumps(s["sample_level_frozen_lr_S_top25"], indent=1, default=str), "```",
                "Composition:", "```json", json.dumps(s["composition"], indent=1, default=str), "```", ""]
    enr = ROOT / "results/enrichment/enrichment_summary.csv"
    if enr.exists():
        out += ["## Enrichment", md(pd.read_csv(enr)), ""]
    dec, ctrl = latest("results/matrix/*_date_dec2004_*"), latest("results/matrix/*_date_control_*")
    if dec and ctrl and (dec / "analysis/stability_summary.csv").exists() and (ctrl / "analysis/stability_summary.csv").exists():
        f = lambda r: pd.read_csv(r / "analysis/stability_summary.csv").query("dimension=='resampling' and k==25").set_index("group").phi_mean
        d = pd.DataFrame({"full": f(full), "dec2004": f(dec), "size_matched_control": f(ctrl)}).reset_index()
        d.to_csv(TAB / "table_date_sensitivity.csv", index=False)
        out += ["## Processing-date sensitivity: resampling Phi at k=25", md(d), ""]
    p = ROOT / "docs/results"; p.mkdir(parents=True, exist_ok=True)
    (p / "results_summary.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", p / "results_summary.md")


if __name__ == "__main__":
    main()
